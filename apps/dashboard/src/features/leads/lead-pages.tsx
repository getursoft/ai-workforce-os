"use client";
import Link from "next/link";
import { useParams, useRouter } from "next/navigation";
import { useEffect, useMemo, useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { AccessGate } from "../admin/authorization";
import { useAuth } from "../auth/auth-provider";
import { createPluginApi } from "../plugins/plugin-api";
import { createAdminApi } from "../admin/api";
import {
  Alert,
  Badge,
  BackLink,
  Button,
  Card,
  Dialog,
  EmptyState,
  Input,
  Label,
  PageHeader,
  Skeleton,
  SummaryCard
} from "../../components/ui";
import {
  createLeadApi,
  type Lead,
  type LeadPriority,
  type LeadSource,
  type LeadStatus
} from "./lead-api";

const key = ["leads"] as const;

function useApi() {
  const { client } = useAuth();
  return useMemo(() => createLeadApi(client), [client]);
}

const STATUSES: LeadStatus[] = ["NEW", "CONTACTED", "QUALIFIED", "FOLLOW_UP", "CONVERTED", "LOST"];
const SOURCES: LeadSource[] = ["WEB_CHAT", "WHATSAPP", "VOICE", "MANUAL", "API", "OTHER"];
const PRIORITIES: LeadPriority[] = ["LOW", "MEDIUM", "HIGH"];

const SOURCE_LABELS: Record<LeadSource, string> = {
  WEB_CHAT: "Web Chat",
  WHATSAPP: "WhatsApp",
  VOICE: "Voice",
  MANUAL: "Manual",
  API: "API",
  OTHER: "Other"
};

function statusTone(status: LeadStatus): "success" | "warning" | "danger" | "neutral" {
  if (status === "CONVERTED") return "success";
  if (status === "LOST") return "danger";
  if (status === "NEW") return "warning";
  return "neutral";
}

function StatusBadge({ status }: Readonly<{ status: LeadStatus }>) {
  return <Badge tone={statusTone(status)}>{status.replace(/_/g, " ")}</Badge>;
}

function formatDate(value: string | null): string {
  if (!value) return "—";
  return new Intl.DateTimeFormat(undefined, { dateStyle: "medium", timeStyle: "short" }).format(new Date(value));
}

function truncate(value: string | null, max = 60): string {
  if (!value) return "—";
  return value.length > max ? `${value.slice(0, max)}…` : value;
}

/** Best-effort AI Employee display-name lookup (installed plugins list) — degrades to a raw id fragment,
 *  never blocks the page, since a user without plugin.read still needs to see their leads. */
function useAgentNames() {
  const { client } = useAuth();
  const pluginApi = useMemo(() => createPluginApi(client), [client]);
  const query = useQuery({
    queryKey: ["leads", "agent-names"],
    queryFn: () => pluginApi.list({ page: 1, pageSize: 100 }),
    retry: false
  });
  return useMemo(() => {
    const map = new Map<string, string>();
    for (const p of query.data?.items ?? []) map.set(p.id, p.displayName);
    return map;
  }, [query.data]);
}

function useAssignableUsers() {
  const { client } = useAuth();
  const adminApi = useMemo(() => createAdminApi(client), [client]);
  const query = useQuery({
    queryKey: ["leads", "assignable-users"],
    queryFn: () => adminApi.listUsers({ page: 1, pageSize: 200 }),
    retry: false
  });
  return query.data?.items ?? [];
}

export function CrmPage() {
  const api = useApi();
  const router = useRouter();
  const agentNames = useAgentNames();
  const [page, setPage] = useState(1);
  const [status, setStatus] = useState<LeadStatus | "">("");
  const [source, setSource] = useState<LeadSource | "">("");
  const [searchInput, setSearchInput] = useState("");
  const [search, setSearch] = useState("");
  const [createOpen, setCreateOpen] = useState(false);

  useEffect(() => {
    const id = setTimeout(() => setSearch(searchInput.trim()), 350);
    return () => clearTimeout(id);
  }, [searchInput]);

  const summaryQuery = useQuery({ queryKey: [...key, "summary"], queryFn: () => api.summary() });
  const listParams = useMemo(
    () => ({
      page,
      pageSize: 20,
      ...(status ? { status } : {}),
      ...(source ? { source } : {}),
      ...(search ? { search } : {})
    }),
    [page, status, source, search]
  );
  const listQuery = useQuery({ queryKey: [...key, "list", listParams], queryFn: () => api.list(listParams) });
  const items = listQuery.data?.items ?? [];

  return (
    <AccessGate permission="leads.read">
      <section className="admin-page">
        <PageHeader
          title="Krevia CRM"
          eyebrow="Krevia CRM"
          description="Manage leads, customer interactions and follow-ups generated by your AI workforce."
          action={
            <AccessGate permission="leads.create">
              <Button onClick={() => setCreateOpen(true)}>New lead</Button>
            </AccessGate>
          }
        />

        <div className="admin-grid" style={{ gridTemplateColumns: "repeat(auto-fit, minmax(140px, 1fr))" }}>
          <SummaryCard title="Total" value={summaryQuery.data?.total ?? "—"} />
          <SummaryCard title="New" value={summaryQuery.data?.new ?? "—"} />
          <SummaryCard title="Qualified" value={summaryQuery.data?.qualified ?? "—"} />
          <SummaryCard title="Follow-up" value={summaryQuery.data?.followUp ?? "—"} />
          <SummaryCard title="Converted" value={summaryQuery.data?.converted ?? "—"} />
        </div>

        <Card className="admin-toolbar" style={{ display: "flex", gap: 12, flexWrap: "wrap", alignItems: "center" }}>
          <Input
            placeholder="Search name, phone, email, reference…"
            value={searchInput}
            onChange={(event) => {
              setSearchInput(event.target.value);
              setPage(1);
            }}
            style={{ minWidth: 240 }}
            aria-label="Search leads"
          />
          <select
            className="ui-input"
            value={status}
            onChange={(event) => {
              setStatus(event.target.value as LeadStatus | "");
              setPage(1);
            }}
            aria-label="Filter by status"
          >
            <option value="">All statuses</option>
            {STATUSES.map((s) => (
              <option key={s} value={s}>{s.replace(/_/g, " ")}</option>
            ))}
          </select>
          <select
            className="ui-input"
            value={source}
            onChange={(event) => {
              setSource(event.target.value as LeadSource | "");
              setPage(1);
            }}
            aria-label="Filter by source"
          >
            <option value="">All sources</option>
            {SOURCES.map((s) => (
              <option key={s} value={s}>{SOURCE_LABELS[s]}</option>
            ))}
          </select>
        </Card>

        {listQuery.isLoading ? (
          <Skeleton />
        ) : listQuery.isError ? (
          <Alert tone="danger" title="Unable to load leads">
            <Button onClick={() => listQuery.refetch()}>Retry</Button>
          </Alert>
        ) : items.length ? (
          <>
            <div className="admin-table-wrap">
              <table className="admin-table">
                <thead>
                  <tr>
                    <th>Lead Ref</th>
                    <th>Customer</th>
                    <th>Contact</th>
                    <th>Source</th>
                    <th>AI Employee</th>
                    <th>Requirement</th>
                    <th>Status</th>
                    <th>Created</th>
                    <th>Last Activity</th>
                  </tr>
                </thead>
                <tbody>
                  {items.map((lead) => (
                    <tr key={lead.id} onClick={() => router.push(`/crm/leads/${lead.id}`)} style={{ cursor: "pointer" }}>
                      <td><strong>{lead.leadReferenceId}</strong></td>
                      <td>{lead.name ?? "—"}</td>
                      <td>{lead.phone ?? lead.email ?? "—"}</td>
                      <td>{SOURCE_LABELS[lead.source]}</td>
                      <td>{lead.agentId ? (agentNames.get(lead.agentId) ?? lead.agentId.slice(0, 8)) : "—"}</td>
                      <td>{truncate(lead.requirement)}</td>
                      <td><StatusBadge status={lead.status} /></td>
                      <td>{formatDate(lead.createdAt)}</td>
                      <td>{formatDate(lead.lastActivityAt)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <div className="admin-pagination">
              <Button disabled={page <= 1} onClick={() => setPage((x) => x - 1)}>Previous</Button>
              <span>Page {page} of {Math.max(1, listQuery.data?.totalPages ?? 1)}</span>
              <Button
                disabled={page >= (listQuery.data?.totalPages ?? 1)}
                onClick={() => setPage((x) => x + 1)}
              >
                Next
              </Button>
            </div>
          </>
        ) : (
          <EmptyState
            title="No leads yet"
            description="A lead is created automatically as soon as your AI workforce captures genuine interest and contact details from a customer — or add one manually."
          />
        )}

        <CreateLeadDialog open={createOpen} onClose={() => setCreateOpen(false)} />
      </section>
    </AccessGate>
  );
}

function CreateLeadDialog({ open, onClose }: Readonly<{ open: boolean; onClose: () => void }>) {
  const api = useApi();
  const qc = useQueryClient();
  const router = useRouter();
  const [name, setName] = useState("");
  const [phone, setPhone] = useState("");
  const [email, setEmail] = useState("");
  const [requirement, setRequirement] = useState("");
  const [priority, setPriority] = useState<LeadPriority>("MEDIUM");

  const createMutation = useMutation({
    mutationFn: () =>
      api.create({
        ...(name ? { name } : {}),
        ...(phone ? { phone } : {}),
        ...(email ? { email } : {}),
        ...(requirement ? { requirement } : {}),
        priority
      }),
    onSuccess: (lead) => {
      void qc.invalidateQueries({ queryKey: key });
      setName("");
      setPhone("");
      setEmail("");
      setRequirement("");
      setPriority("MEDIUM");
      onClose();
      router.push(`/crm/leads/${lead.id}`);
    }
  });

  return (
    <Dialog
      open={open}
      title="New lead"
      description="Manually add a lead to Krevia CRM."
      confirmLabel="Create lead"
      onCancel={onClose}
      onConfirm={() => createMutation.mutate()}
    >
      <div className="ui-field">
        <Label htmlFor="lead-name">Customer name</Label>
        <Input id="lead-name" value={name} onChange={(e) => setName(e.target.value)} />
      </div>
      <div className="ui-field">
        <Label htmlFor="lead-phone">Phone</Label>
        <Input id="lead-phone" value={phone} onChange={(e) => setPhone(e.target.value)} />
      </div>
      <div className="ui-field">
        <Label htmlFor="lead-email">Email</Label>
        <Input id="lead-email" type="email" value={email} onChange={(e) => setEmail(e.target.value)} />
      </div>
      <div className="ui-field">
        <Label htmlFor="lead-requirement">Requirement</Label>
        <textarea
          id="lead-requirement"
          className="ui-input"
          rows={3}
          value={requirement}
          onChange={(e) => setRequirement(e.target.value)}
        />
      </div>
      <div className="ui-field">
        <Label htmlFor="lead-priority">Priority</Label>
        <select
          id="lead-priority"
          className="ui-input"
          value={priority}
          onChange={(e) => setPriority(e.target.value as LeadPriority)}
        >
          {PRIORITIES.map((p) => (
            <option key={p} value={p}>{p}</option>
          ))}
        </select>
      </div>
      {createMutation.isError ? <Alert tone="danger" title="Unable to create lead" /> : null}
    </Dialog>
  );
}

export function LeadDetailPage() {
  const { id } = useParams<{ id: string }>();
  const api = useApi();
  const qc = useQueryClient();
  const agentNames = useAgentNames();
  const users = useAssignableUsers();
  const [note, setNote] = useState("");

  const leadQuery = useQuery({ queryKey: [...key, id], queryFn: () => api.get(id) });
  const activityQuery = useQuery({ queryKey: [...key, id, "activity"], queryFn: () => api.activity(id) });

  const invalidate = () => {
    void qc.invalidateQueries({ queryKey: [...key, id] });
    void qc.invalidateQueries({ queryKey: [...key, id, "activity"] });
    void qc.invalidateQueries({ queryKey: [...key, "summary"] });
  };

  const statusMutation = useMutation({
    mutationFn: (status: LeadStatus) => api.update(id, { status }),
    onSuccess: invalidate
  });
  const assignMutation = useMutation({
    mutationFn: (assignedToUserId: string | null) => api.assign(id, assignedToUserId),
    onSuccess: invalidate
  });
  const noteMutation = useMutation({
    mutationFn: (text: string) => api.addNote(id, text),
    onSuccess: () => {
      setNote("");
      invalidate();
    }
  });

  if (leadQuery.isLoading) return <Skeleton />;
  if (!leadQuery.data) return <EmptyState title="Lead not found" description="It may not exist or you may not have access." />;
  const lead: Lead = leadQuery.data;
  const assignee = users.find((u) => u.id === lead.assignedToUserId);

  return (
    <AccessGate permission="leads.read">
      <section className="admin-page">
        <header className="admin-page__header">
          <div>
            <BackLink href="/crm" label="Back to Krevia CRM" />
            <h1>{lead.name ?? "Unnamed lead"}</h1>
            <p>{lead.leadReferenceId} · {SOURCE_LABELS[lead.source]} · Created {formatDate(lead.createdAt)}</p>
          </div>
          <StatusBadge status={lead.status} />
        </header>

        <Card>
          <h2>Summary</h2>
          <div className="admin-grid">
            <div><Label>Phone</Label><p>{lead.phone ?? "—"}</p></div>
            <div><Label>Email</Label><p>{lead.email ?? "—"}</p></div>
            <div><Label>Priority</Label><p>{lead.priority}</p></div>
            <div><Label>Source</Label><p>{SOURCE_LABELS[lead.source]}</p></div>
            <div><Label>AI Employee</Label><p>{lead.agentId ? (agentNames.get(lead.agentId) ?? lead.agentId) : "—"}</p></div>
            <div><Label>Assigned to</Label><p>{assignee ? `${assignee.firstName} ${assignee.lastName ?? ""}`.trim() : "Unassigned"}</p></div>
            {lead.interactionId ? (
              <div><Label>Interaction</Label><p><Link href={`/interactions/${lead.interactionId}`}>View interaction</Link></p></div>
            ) : null}
            <div><Label>Last activity</Label><p>{formatDate(lead.lastActivityAt)}</p></div>
            {lead.convertedAt ? <div><Label>Converted</Label><p>{formatDate(lead.convertedAt)}</p></div> : null}
            {lead.lostAt ? <div><Label>Lost</Label><p>{formatDate(lead.lostAt)}</p></div> : null}
          </div>
          {lead.requirement ? (
            <div style={{ marginTop: 16 }}>
              <Label>Requirement / Summary</Label>
              <p style={{ marginTop: 4, whiteSpace: "pre-wrap" }}>{lead.requirement}</p>
            </div>
          ) : null}
        </Card>

        <AccessGate permission="leads.update">
          <Card>
            <h2>Update status</h2>
            <div style={{ display: "flex", gap: 8, flexWrap: "wrap" }}>
              {STATUSES.map((option) => (
                <Button
                  key={option}
                  variant={option === lead.status ? "primary" : "secondary"}
                  disabled={statusMutation.isPending || option === lead.status}
                  loading={statusMutation.isPending && statusMutation.variables === option}
                  onClick={() => statusMutation.mutate(option)}
                >
                  {option.replace(/_/g, " ")}
                </Button>
              ))}
            </div>
          </Card>
        </AccessGate>

        <AccessGate permission="leads.assign">
          <Card>
            <h2>Assign</h2>
            <div style={{ display: "flex", gap: 8, alignItems: "center" }}>
              <select
                className="ui-input"
                value={lead.assignedToUserId ?? ""}
                onChange={(event) => assignMutation.mutate(event.target.value || null)}
                aria-label="Assign lead"
                disabled={assignMutation.isPending}
              >
                <option value="">Unassigned</option>
                {users.map((u) => (
                  <option key={u.id} value={u.id}>{u.firstName} {u.lastName ?? ""}</option>
                ))}
              </select>
            </div>
          </Card>
        </AccessGate>

        <AccessGate permission="leads.notes">
          <Card>
            <h2>Add note</h2>
            <textarea
              className="ui-input"
              rows={3}
              value={note}
              onChange={(event) => setNote(event.target.value)}
              placeholder="Add a note about this lead…"
              aria-label="New note"
            />
            <div style={{ marginTop: 8 }}>
              <Button
                disabled={!note.trim() || noteMutation.isPending}
                loading={noteMutation.isPending}
                onClick={() => noteMutation.mutate(note.trim())}
              >
                Add note
              </Button>
            </div>
          </Card>
        </AccessGate>

        <Card>
          <h2>Activity timeline</h2>
          {activityQuery.isLoading ? (
            <Skeleton />
          ) : activityQuery.data?.length ? (
            <ul className="ui-timeline">
              {activityQuery.data.map((entry) => (
                <li key={entry.id}>
                  <strong>{entry.type.replace(/_/g, " ")}</strong>
                  <span> · {formatDate(entry.createdAt)}</span>
                  {entry.note ? <p>{entry.note}</p> : null}
                </li>
              ))}
            </ul>
          ) : (
            <p>No activity recorded yet.</p>
          )}
        </Card>
      </section>
    </AccessGate>
  );
}
