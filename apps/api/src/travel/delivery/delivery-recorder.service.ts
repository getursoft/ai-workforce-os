import { Injectable, Logger } from "@nestjs/common";
import { PrismaService } from "../../infrastructure/prisma/prisma.service";
import { PluginSecretsEncryptionService, type EncryptedPayload } from "../../plugins/plugin.runtime";
import { EmailService, EmailNotConfiguredError } from "../../notifications/email.service";
import { EmailConfigurationService } from "../../plugins/email-configuration.service";
import { uploadMetaWhatsAppMedia, sendMetaWhatsAppDocument } from "../../channels/whatsapp/meta-whatsapp.client";
import { TicketGeneratorService } from "./ticket-generator.service";

export interface DeliveryRecord {
  channel: "email" | "whatsapp";
  recipient: string;
  status: "SENT" | "FAILED" | "SKIPPED";
  messageId: string | null;
  errorCode: string | null;
  sentAt: string;
}

/**
 * Actually sends the generated ticket PDF by email and/or WhatsApp — replaces the previous
 * `simulateDelivery` stub, which faked a "DELIVERED" status with a random message ID and never sent
 * anything anywhere. Both channels are best-effort and independent: a failed email never blocks a
 * WhatsApp send or vice versa, and neither ever blocks the booking itself from being marked
 * TICKETS_DELIVERED (a real ticket was generated; a failed *notification* about it is a separate,
 * recorded fact — see `emailDeliveryStatus`/`mobileDeliveryStatus`). Every status is what actually
 * happened, never a fabricated success.
 */
@Injectable()
export class DeliveryRecorderService {
  private readonly logger = new Logger(DeliveryRecorderService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly ticketGenerator: TicketGeneratorService,
    private readonly email: EmailService,
    private readonly emailConfig: EmailConfigurationService,
    private readonly secrets: PluginSecretsEncryptionService
  ) {}

  async recordTicketDelivery(bookingId: string, organizationId: string): Promise<{
    email: DeliveryRecord | null;
    whatsapp: DeliveryRecord | null;
  }> {
    const booking = await this.prisma.travelBooking.findFirst({
      where: { id: bookingId, organizationId },
    });
    if (!booking) throw new Error(`Booking ${bookingId} not found`);

    const [pkg, pdf] = await Promise.all([
      this.ticketGenerator.generateTicketPackage(bookingId, organizationId),
      this.ticketGenerator.generatePdfContent(bookingId, organizationId),
    ]);
    const filename = `ticket-${bookingId.slice(0, 8)}.pdf`;

    const emailDelivery = booking.customerEmail
      ? await this.sendEmail(organizationId, booking.pluginInstallationId, booking.customerEmail, pkg.pnr, filename, pdf)
      : null;
    const whatsappDelivery = booking.customerPhone
      ? await this.sendWhatsApp(organizationId, booking.pluginInstallationId, booking.customerPhone, pkg.pnr, filename, pdf)
      : null;

    await this.prisma.travelBooking.update({
      where: { id: bookingId },
      data: {
        emailDeliveryStatus: emailDelivery?.status ?? null,
        mobileDeliveryStatus: whatsappDelivery?.status ?? null,
        status: "TICKETS_DELIVERED",
      },
    });

    this.logger.log({
      event: "TICKET_DELIVERY_COMPLETED",
      bookingId,
      emailStatus: emailDelivery?.status ?? "SKIPPED",
      whatsappStatus: whatsappDelivery?.status ?? "SKIPPED",
    });

    return { email: emailDelivery, whatsapp: whatsappDelivery };
  }

  private async sendEmail(
    organizationId: string,
    pluginInstallationId: string,
    to: string,
    pnr: string,
    filename: string,
    pdf: Buffer
  ): Promise<DeliveryRecord> {
    const sentAt = new Date().toISOString();
    try {
      const smtp = await this.emailConfig.resolve(organizationId, pluginInstallationId);
      const result = await this.email.sendMail({
        to,
        subject: `Your travel ticket — PNR ${pnr}`,
        text: `Your booking is confirmed. PNR: ${pnr}. Your e-ticket is attached as a PDF.\n\nThis is a simulated ticket generated by the AI Workforce OS demo environment — not a real booking.`,
        attachments: [{ filename, content: pdf, contentType: "application/pdf" }],
        ...(smtp ? { smtp } : {}),
      });
      return { channel: "email", recipient: to, status: "SENT", messageId: result.messageId, errorCode: null, sentAt };
    } catch (error) {
      const errorCode = error instanceof EmailNotConfiguredError ? "EMAIL_NOT_CONFIGURED" : "EMAIL_SEND_FAILED";
      this.logger.warn({ event: "TICKET_EMAIL_DELIVERY_FAILED", to, errorCode, error: error instanceof Error ? error.message : "unknown" });
      return { channel: "email", recipient: to, status: "FAILED", messageId: null, errorCode, sentAt };
    }
  }

  private async sendWhatsApp(
    organizationId: string,
    pluginInstallationId: string,
    to: string,
    pnr: string,
    filename: string,
    pdf: Buffer
  ): Promise<DeliveryRecord> {
    const sentAt = new Date().toISOString();
    const channel = await this.findWhatsAppChannel(organizationId, pluginInstallationId);
    if (!channel) {
      return { channel: "whatsapp", recipient: to, status: "SKIPPED", messageId: null, errorCode: "WHATSAPP_CHANNEL_NOT_CONFIGURED", sentAt };
    }
    try {
      const secrets = this.secrets.decrypt(channel.encryptedSecrets as unknown as EncryptedPayload);
      const accessToken = secrets.accessToken;
      const phoneNumberId = channel.phoneNumberId;
      if (!accessToken || !phoneNumberId) {
        return { channel: "whatsapp", recipient: to, status: "SKIPPED", messageId: null, errorCode: "WHATSAPP_CREDENTIALS_MISSING", sentAt };
      }
      const { mediaId } = await uploadMetaWhatsAppMedia({
        phoneNumberId, accessToken, buffer: pdf, filename, mimeType: "application/pdf",
      });
      const result = await sendMetaWhatsAppDocument({
        phoneNumberId, accessToken, to, mediaId, filename, caption: `Your ticket — PNR ${pnr}`,
      });
      return { channel: "whatsapp", recipient: to, status: "SENT", messageId: result.providerMessageId, errorCode: null, sentAt };
    } catch (error) {
      this.logger.warn({ event: "TICKET_WHATSAPP_DELIVERY_FAILED", to, error: error instanceof Error ? error.message : "unknown" });
      return { channel: "whatsapp", recipient: to, status: "FAILED", messageId: null, errorCode: "WHATSAPP_SEND_FAILED", sentAt };
    }
  }

  /** Prefers a WhatsApp channel assigned to the booking's own plugin installation (the Travel Employee
   *  that actually took this booking); falls back to any other active WhatsApp channel the org has
   *  connected, since a single business WhatsApp number is commonly shared across employees. */
  private async findWhatsAppChannel(organizationId: string, pluginInstallationId: string) {
    const assigned = await this.prisma.channelConnection.findFirst({
      where: {
        organizationId,
        pluginInstallationId,
        channelType: "WHATSAPP",
        provider: "META_CLOUD_API",
        status: "ACTIVE",
        deletedAt: null,
      },
    });
    if (assigned) return assigned;
    return this.prisma.channelConnection.findFirst({
      where: {
        organizationId,
        channelType: "WHATSAPP",
        provider: "META_CLOUD_API",
        status: "ACTIVE",
        deletedAt: null,
      },
      orderBy: { createdAt: "desc" },
    });
  }
}
