import PDFDocument from "pdfkit";

/**
 * Renders arbitrary legal document text (a drafted notice, reply, case summary) into a clean, well-formatted
 * A4 PDF via pdfkit (the same pure-Node library the Travel ticket generator uses). The content is parsed
 * into headings, paragraphs, and bullet lines so the PDF reads professionally rather than as raw text.
 */
export class LegalPdfService {
  async generatePdf(title: string, content: string): Promise<Buffer> {
    return new Promise<Buffer>((resolve, reject) => {
      const doc = new PDFDocument({ size: "A4", margin: 56 });
      const chunks: Buffer[] = [];
      doc.on("data", (chunk: Buffer) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      // Header
      doc
        .fontSize(16)
        .font("Helvetica-Bold")
        .fillColor("#1a1a1a")
        .text(title, { align: "center" });
      doc
        .moveDown(0.4)
        .moveTo(56, doc.y)
        .lineTo(539, doc.y)
        .strokeColor("#b08968")
        .stroke();
      doc.moveDown(1);

      // Body — split into lines, treat "**heading**"/"### x" as headings and "• "/"- " lines as bullets.
      const lines = content.split(/\r?\n/);
      for (const raw of lines) {
        const line = raw.trimEnd();
        if (!line.trim()) {
          doc.moveDown(0.3);
          continue;
        }
        const heading = line.match(/^#{1,3}\s+(.+)$/);
        if (heading && heading[1]) {
          doc.moveDown(0.5);
          doc.fontSize(12).font("Helvetica-Bold").fillColor("#1a1a1a").text(heading[1].trim());
          doc.fontSize(10.5).font("Helvetica");
          continue;
        }
        if (line.startsWith("• ") || line.startsWith("- ") || line.startsWith("* ")) {
          const bullet = line.slice(2).trim();
          doc
            .font("Helvetica")
            .fontSize(10.5)
            .fillColor("#2b2b2b")
            .text(`• ${bullet}`, { indent: 10, lineGap: 3 });
          continue;
        }
        doc.font("Helvetica").fontSize(10.5).fillColor("#2b2b2b").text(line, { lineGap: 4 });
      }

      // Footer
      doc.moveDown(1.5);
      doc
        .fontSize(8.5)
        .fillColor("#888888")
        .text(
          "Draft generated by the Krevia.ai Legal Employee. This is a draft for professional review — not legal advice. Every draft is reviewed and filed by a licensed CA or advocate.",
          { align: "center" }
        );

      doc.end();
    });
  }
}
